"""The published benchmark: fixed situations, a generated table."""

import sys
import time
from dataclasses import dataclass
from pathlib import Path

from emitter_optimizer.engine.laws import load_law_file
from emitter_optimizer.engine.maps import (
    CollisionMap,
    DensityMap,
    load_collisions,
    load_density,
)
from emitter_optimizer.engine.solver import Solver
from emitter_optimizer.paths import (
    DEFAULT_EMITTER_FUNCTION,
    DEFAULT_SENSOR_FUNCTION,
    PROJECT_ROOT,
)

DEFAULT_OUTPUT = PROJECT_ROOT / "docs" / "benchmark" / "results.md"
RESOURCES = PROJECT_ROOT / "resources" / "map"
ITERATIONS = 60
EMITTERS = 15
SEED = 0
LEARNING_RATE = 1.0


@dataclass(frozen=True)
class Situation:
    name: str
    density: DensityMap | None
    collisions: CollisionMap | None
    map_scale: tuple[float, float]
    grid_size: tuple[int, int]

    @property
    def cells(self) -> int:
        return self.grid_size[0] * self.grid_size[1]


@dataclass(frozen=True)
class Result:
    situation: Situation
    emitters: int
    initial_gain: float
    gain: float
    seconds: float

    @property
    def improvement(self) -> float:
        return self.gain - self.initial_gain


def situations() -> tuple[Situation, ...]:
    density = load_density(RESOURCES / "value_001.png")
    walls = load_collisions(RESOURCES / "collide_001.png")
    return (
        Situation("uniform", None, None, (100.0, 100.0), (32, 32)),
        Situation("density", density, None, (100.0, 100.0), (32, 32)),
        Situation("walls", density, walls, (100.0, 100.0), (32, 32)),
        Situation("wide", density, None, (100.0, 50.0), (32, 64)),
    )


def measure(
    situation: Situation,
    *,
    iterations: int,
    emitters: int,
    seed: int,
) -> Result:
    solver = Solver(
        n_emitters=emitters,
        density_map=situation.density,
        collision_map=situation.collisions,
        map_scale=situation.map_scale,
        grid_size=situation.grid_size,
        emitter_law=load_law_file(DEFAULT_EMITTER_FUNCTION),
        sensor_law=load_law_file(DEFAULT_SENSOR_FUNCTION),
        n_iteration=iterations,
        epsilon=LEARNING_RATE,
        seed=seed,
    )
    initial_gain = solver.field.gain(solver.emitters_positions)
    started = time.perf_counter()
    solver.solve()
    seconds = time.perf_counter() - started
    gain = solver.field.gain(solver.emitters_positions)
    return Result(situation, emitters, initial_gain, gain, seconds)


def report(results: tuple[Result, ...], *, iterations: int) -> str:
    lines = [
        "# Benchmark",
        "",
        f"Generated by `just bench`: {iterations} iterations, seed {SEED}, "
        f"learning rate {LEARNING_RATE}. Never edited by hand.",
        "",
        "| Situation | Cells | Emitters | Initial | Final | Improvement "
        "| Seconds | Improvement per second |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for result in results:
        per_second = (
            result.improvement / result.seconds if result.seconds > 0.0 else 0.0
        )
        lines.append(
            f"| {result.situation.name} | {result.situation.cells} "
            f"| {result.emitters} | {result.initial_gain:.4f} "
            f"| {result.gain:.4f} | {result.improvement:+.4f} "
            f"| {result.seconds:.3f} | {per_second:+.2f} |"
        )
    return "\n".join(lines) + "\n"


def main(arguments: list[str] | None = None) -> int:
    output = Path(arguments[0]) if arguments else DEFAULT_OUTPUT
    results = tuple(
        measure(situation, iterations=ITERATIONS, emitters=EMITTERS, seed=SEED)
        for situation in situations()
    )
    text = report(results, iterations=ITERATIONS)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
