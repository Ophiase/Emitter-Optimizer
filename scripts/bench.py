from emitter_optimizer.paths import PROJECT_ROOT
from scripts.situations import (
    ITERATIONS,
    SEED,
    Result,
    measure,
    situations,
)

OUTPUT = PROJECT_ROOT / "docs" / "benchmark" / "results.md"
FIGURES = PROJECT_ROOT / "docs" / "benchmark"


def report(results: tuple[Result, ...]) -> str:
    lines = [
        "# Benchmark",
        "",
        f"Generated by `just bench`: {ITERATIONS} iterations, seed {SEED}. "
        "Never edited by hand.",
        "",
        "| Case | What it is | Cells | Initial | Final | Improvement | Seconds |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for result in results:
        situation = result.situation
        lines.append(
            f"| {situation.name} | {situation.description} | {situation.cells} "
            f"| {result.initial_gain:.4f} | {result.gain:.4f} "
            f"| {result.improvement:+.4f} | {result.seconds:.3f} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    FIGURES.mkdir(parents=True, exist_ok=True)
    results = tuple(measure(situation) for situation in situations())
    for result in results:
        result.solver.make_fig().savefig(FIGURES / f"{result.situation.name}.png")
    text = report(results)
    OUTPUT.write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
